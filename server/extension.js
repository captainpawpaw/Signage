// Builds the browser add-on. Every build carries the server's public keys
// (pinned: the player ignores anything not signed by them) and every address
// the server is reachable at, so screens find it without typing an IP.
//   universal add-on:      shows a pairing code, approved in the console
//   pre-configured add-on: also carries a one-time enrolment token for one screen
import fs from 'node:fs/promises';
import path from 'node:path';
import JSZip from 'jszip';
import { fileURLToPath } from 'node:url';
import { buildCrx3, extensionId } from './crypto.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PLAYER_FILES = ['player.html', 'player.js', 'player.css'];
const EXTENSION_FILES = ['background.js', 'icon-48.png', 'icon-128.png'];
const SCREEN_SETUP_FILES = ['setup-screen.bat', 'setup-screen.ps1', 'update-addon.ps1'];

// Bump whenever player/ or extension/ changes so installed add-ons update.
export const ADDON_VERSION = '2.2.0';

export function addonId(keys) {
  return extensionId(keys.addonPub);
}

export function addonConfig({ keys, settings, candidates, screen }) {
  return {
    serverId: settings.serverId,
    serverName: settings.serverName,
    candidates,
    signKey: keys.signPub.toString('base64'),
    ecdhKey: keys.ecdhPub.toString('base64'),
    fingerprint: keys.fingerprint,
    ...(screen ? { enrollToken: screen.enrollToken, screenName: screen.name } : {}),
  };
}

function addonManifest({ keys, settings, screen, browser, updateBase }) {
  const name = (screen ? `Signage – ${screen.name}` : `Signage Player – ${settings.serverName}`).slice(0, 75);
  const common = {
    manifest_version: 3,
    name,
    short_name: 'Signage',
    version: ADDON_VERSION,
    description: `Digital signage player for ${settings.serverName}. Content is end-to-end encrypted and signed by the server.`,
    action: { default_title: name, default_icon: { 48: 'icon-48.png' } },
    icons: { 48: 'icon-48.png', 128: 'icon-128.png' },
  };
  if (browser === 'firefox') {
    return {
      ...common,
      background: { scripts: ['config.js', 'background.js'] },
      permissions: ['tabs', 'alarms', 'storage'],
      browser_specific_settings: { gecko: { id: `signage-${settings.serverId.slice(0, 12).toLowerCase()}@signage.local`, strict_min_version: '115.0' } },
    };
  }
  return {
    ...common,
    // The public key pins the extension ID, so unpacked, pre-configured and
    // CRX installs are all the same extension and keep the same device keys.
    key: keys.addonPub.toString('base64'),
    ...(updateBase ? { update_url: `${updateBase}/addon/updates.xml` } : {}),
    background: { service_worker: 'background.js' },
    permissions: ['tabs', 'alarms', 'storage', 'power'],
  };
}

async function addonFiles(opts) {
  const config = addonConfig(opts);
  const files = {
    'manifest.json': JSON.stringify(addonManifest(opts), null, 2),
    'config.js': `// Generated by the Signage server${opts.screen ? ` for screen "${opts.screen.name}". Contains a one-time enrolment token` : ''}.\nself.SIGNAGE_CONFIG = ${JSON.stringify(config, null, 2)};\n`,
  };
  for (const f of PLAYER_FILES) files[f] = await fs.readFile(path.join(ROOT, 'player', f));
  for (const f of EXTENSION_FILES) files[f] = await fs.readFile(path.join(ROOT, 'extension', f));
  return files;
}

const zipOf = (files, prefix = '') => {
  const zip = new JSZip();
  for (const [name, data] of Object.entries(files)) zip.file(prefix + name, data);
  return zip;
};

// opts: { keys, settings, candidates, updateBase, browser: 'chrome'|'firefox', screen? }
export async function buildAddonZip(opts) {
  return zipOf(await addonFiles(opts)).generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

export async function buildAddonCrx(opts) {
  return buildCrx3(await buildAddonZip({ ...opts, browser: 'chrome', screen: null }), opts.keys.addonKey);
}

export function updatesXml({ keys, updateBase }) {
  return `<?xml version='1.0' encoding='UTF-8'?>
<gupdate xmlns='http://www.google.com/update2/response' protocol='2.0'>
  <app appid='${addonId(keys)}'>
    <updatecheck codebase='${updateBase}/addon/signage.crx' version='${ADDON_VERSION}' />
  </app>
</gupdate>
`;
}

// Windows installer for screen PCs: the universal add-on plus scripts that set
// up kiosk start-up and keep the add-on updated (verifying the server signature).
export async function buildScreenSetupZip(opts) {
  const zip = zipOf(await addonFiles({ ...opts, browser: 'chrome', screen: null }), 'addon/');
  for (const f of SCREEN_SETUP_FILES) zip.file(f, await fs.readFile(path.join(ROOT, 'windows', 'screen', f)));
  zip.file('server.json', JSON.stringify({
    serverId: opts.settings.serverId,
    serverName: opts.settings.serverName,
    candidates: opts.candidates,
    extensionId: addonId(opts.keys),
    // Raw P-256 point (X||Y) of the signing key, for .NET's ECDsaCng in update-addon.ps1.
    signKeyXY: opts.keys.signPub.subarray(opts.keys.signPub.length - 64).toString('base64'),
  }, null, 2));
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}
