# Registers the Signage server as a scheduled task that starts when Windows
# boots (before anyone logs in), runs in the background as SYSTEM, and is
# restarted if it stops. Re-run it after moving the folder or installing tools
# such as ffmpeg, LibreOffice or poppler, so the server picks them up.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$taskName = 'Signage Server'

$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) {
  Write-Host 'Node.js was not found. Install it from https://nodejs.org and try again.' -ForegroundColor Red
  exit 1
}
$port = if ($env:PORT) { $env:PORT } else { '8080' }

Write-Host 'Installing dependencies...'
Push-Location $root
try { & npm.cmd install --no-audit --no-fund --loglevel=error } finally { Pop-Location }
if ($LASTEXITCODE -ne 0) { throw 'npm install failed' }

# Stop a copy started by hand (start-signage.bat) so the port is free.
Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" |
  Where-Object { $_.CommandLine -match 'server[\\/]index\.js' } |
  ForEach-Object { Stop-Process -Id $_.ProcessId -Force }

New-Item -ItemType Directory -Force -Path (Join-Path $root 'data') | Out-Null
$runner = Join-Path $PSScriptRoot 'run-server.cmd'
# The task runs as SYSTEM, which has a different PATH: copy this user's PATH so
# tools installed with winget (ffmpeg, poppler) are found. "ping" is the delay
# because "timeout" fails without a console.
$lines = @(
  '@echo off',
  'rem Generated by install-autostart.ps1 - run that again instead of editing this file.',
  "set ""PATH=$env:PATH""",
  "set ""PORT=$port""",
  "cd /d ""$root""",
  ':loop',
  """$node"" server\index.js >> ""$root\data\server.log"" 2>&1",
  'ping -n 6 127.0.0.1 >nul',
  'goto loop'
)
Set-Content -Path $runner -Value $lines -Encoding Default

$action = New-ScheduledTaskAction -Execute 'cmd.exe' -Argument "/c ""$runner"""
$trigger = New-ScheduledTaskTrigger -AtStartup
$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 `
  -RestartInterval (New-TimeSpan -Minutes 1) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
  -StartWhenAvailable -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null

# Let screens and phones on the local network reach the server (web + mDNS).
Get-NetFirewallRule -DisplayName 'Signage Server*' -ErrorAction SilentlyContinue | Remove-NetFirewallRule
New-NetFirewallRule -DisplayName 'Signage Server (web)' -Direction Inbound -Action Allow -Protocol TCP -LocalPort $port -Profile Domain,Private | Out-Null
New-NetFirewallRule -DisplayName 'Signage Server (mDNS)' -Direction Inbound -Action Allow -Protocol UDP -LocalPort 5353 -Profile Domain,Private | Out-Null

Start-ScheduledTask -TaskName $taskName
Start-Sleep -Seconds 3

Write-Host ''
Write-Host 'The Signage server now starts automatically with Windows.' -ForegroundColor Green
Write-Host "  On this PC:      http://localhost:$port/admin/"
Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
  Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' } |
  ForEach-Object { Write-Host "  On the network:  http://$($_.IPAddress):$port/admin/" }
Write-Host "  Also try:        http://signage.local:$port/admin/"
Write-Host "  Log file:        $root\data\server.log"
if (Get-NetConnectionProfile -ErrorAction SilentlyContinue | Where-Object NetworkCategory -eq 'Public') {
  Write-Host ''
  Write-Host 'Warning: this PC is on a network marked "Public", so other devices cannot reach it.' -ForegroundColor Yellow
  Write-Host 'Settings > Network & internet > your connection > set Network profile to Private.' -ForegroundColor Yellow
}
